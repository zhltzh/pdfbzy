export default function ScannedPdfToTextPage() {
  return (
    <GuideArticle guide={guide} faq={faq}>
      <p>
        扫描件 PDF 里的文字选不中、复制出来是空白，是因为整页其实是一张图片。要把它变成可编辑、可搜索的文字，需要
        OCR（光学字符识别）。下面用浏览器里的免费 OCR 工具，把扫描 PDF 转成可复制的文本，并说明哪些情况识别率会明显下降。
      </p>

      <h2>先确认：你的 PDF 是不是「假 PDF」</h2>
      <p>
        打开 PDF，试着用鼠标选中一段文字。如果完全选不中、搜索也搜不到关键词，说明页面是图片（扫描件或拍照生成），这类文件才需要
        OCR。如果文字能正常选中，直接复制即可，不需要识别。
      </p>
      <p>
        还有一种混合情况：文件里既有文字层又有扫描页。可以先检查目录页是否能选中，再决定是否整份识别，避免把本来清晰的文字又识别一遍。
      </p>

      <h2>扫描件 PDF 转文字的操作步骤</h2>
      <ol>
        <li>打开「OCR 文字识别」工具。</li>
        <li>
          上传扫描件 PDF，或直接传 JPG、PNG、WEBP 图片。一次最多 10 个文件，单个 50MB；多页 PDF 会逐页识别。
        </li>
        <li>
          选择识别语言：中文材料选「仅中文」，英文选「仅英文」，中英混排（论文、说明书）选默认的「中文 +
          英文」。
        </li>
        <li>
          点击开始识别。首次使用需要下载识别语言包，之后浏览器会缓存；识别全程在本地运行，文件不会上传。
        </li>
        <li>
          识别完成后可以一键复制，或下载为 TXT；需要把结果整理成文档时，也可以下载为纯文字 PDF。
        </li>
      </ol>

      <GuideToolCta
        href="/ocr-text"
        label="OCR 文字识别（扫描件转可复制文字）"
        description="支持 PDF 与图片，中文、英文、中英混合三种语言模式，本地识别不上传。"
      />

      <h2>提高识别率的 5 个技巧</h2>
      <ol>
        <li>
          <strong>扫描分辨率不低于 300dpi。</strong>150dpi 以下的小字，笔画容易断，任何 OCR 都救不回来。手机拍照时尽量让文字占满画面。
        </li>
        <li>
          <strong>把页面摆正。</strong>扫描歪斜超过 5 度，行会被切碎。可以先用
          <a href="/rotate-pdf">旋转 PDF</a>
          校正，再识别。
        </li>
        <li>
          <strong>裁掉黑边和装订阴影。</strong>用
          <a href="/crop-pdf">裁剪 PDF</a>
          去掉页面四周的暗边和手指、桌面等干扰。
        </li>
        <li>
          <strong>单栏排版优先。</strong>双栏、三栏的报纸或论文，识别结果容易串行。建议按栏裁剪后分两次识别。
        </li>
        <li>
          <strong>中英混排不要只选中文。</strong>英文单词会被当成生僻字，选「中文 + 英文」更稳；纯英文材料则选「仅英文」更准。
        </li>
      </ol>

      <h2>OCR 做不到的事</h2>
      <ul>
        <li>
          <strong>不保留原版式。</strong>表格会变成按行排列的文字，需要回到 Excel 手工整理；图片、流程图、页眉页脚也会混进正文。
        </li>
        <li>
          <strong>手写体、艺术字、印章文字识别率低。</strong>签名、批注、骑缝章等内容要人工核对。
        </li>
        <li>
          <strong>公式、上下标、竖排文字容易出错。</strong>数学公式基本只能识别出零散符号。
        </li>
        <li>
          <strong>不会自动断句。</strong>识别结果按视觉行输出，长段落需要自己合并、分段。
        </li>
      </ul>
      <p>
        所以 OCR 的定位是「把文字捞出来」，而不是「还原排版」。重要合同、票据识别后务必逐段校对，尤其是数字、金额、身份证号和日期，这些字段错一位都可能出问题。
      </p>

      <h2>识别出来的文本怎么用</h2>
      <p>
        TXT 适合再粘进 Word、飞书或笔记软件，保留纯文本便于二次编辑；纯文字 PDF
        适合直接归档，或发给不方便接收 TXT 的人。如果原文只需要其中几页，先用
        <a href="/extract-pages">提取页面</a>
        截取，再识别，能省一半时间。
      </p>
      <p>
        反过来，如果 PDF 本身是文字型，只是想提取某些页的文字，不必 OCR——直接选中复制，或用提取页面导出那几页即可。
      </p>
    </GuideArticle>
  );
}
